// ─── describeThrown (#160) ────────────────────────────────────────────

test('describeThrown: Error keeps its message (the shape audit logs already showed)', () => {
	const err = new TypeError('eda.dmt_Project.getAllProjects is not a function');
	assert.equal(describeThrown(err), 'eda.dmt_Project.getAllProjects is not a function');
});

test('describeThrown: Error with empty message falls back to its name', () => {
	assert.equal(describeThrown(new RangeError('')), 'RangeError');
});

test('describeThrown: bare object is NOT flattened to [object Object]', () => {
	const detail = describeThrown({ code: 'ERR_X', message: 'boom' });
	assert.notEqual(detail, '[object Object]');
	assert.equal(detail, '[ERR_X] boom | {"code":"ERR_X","message":"boom"}');
});

test('describeThrown: message-like key is picked in precedence order', () => {
	assert.match(describeThrown({ msg: 'from msg' }), /^from msg \|/);
	assert.match(describeThrown({ error: 'from error' }), /^from error \|/);
	assert.match(describeThrown({ message: 'wins', msg: 'loses' }), /^wins \|/);
});

test('describeThrown: object without any message-like key still renders its fields', () => {
	assert.equal(describeThrown({ status: 500, path: '/x' }), '{"status":500,"path":"/x"}');
});

test('describeThrown: circular object does not throw and marks the cycle', () => {
	const cyclic: Record<string, unknown> = { name: 'loop' };
	cyclic.self = cyclic;
	const detail = describeThrown(cyclic);
	assert.match(detail, /\[Circular\]/);
	assert.notEqual(detail, '[object Object]');
});

test('describeThrown: object with no enumerable properties says so instead of [object Object]', () => {
	assert.equal(describeThrown(Object.create(null)), '[object Object] (no enumerable properties)');
});

test('describeThrown: primitives and nullish values render readably', () => {
	assert.equal(describeThrown('plain string'), 'plain string');
	assert.equal(describeThrown(null), 'null');
	assert.equal(describeThrown(undefined), 'undefined');
	assert.equal(describeThrown(42), '42');
	assert.equal(describeThrown(false), 'false');
});

test('describeThrown: oversized detail is truncated and flagged, message stays at the front', () => {
	const fat = { message: 'the readable part', blob: 'x'.repeat(5000) };
	const detail = describeThrown(fat);
	assert.ok(detail.length < 5000);
	assert.ok(detail.startsWith('the readable part'));
	assert.match(detail, /truncated, \d+ chars total/);
	assert.ok(detail.length <= THROWN_DETAIL_MAX + 40);
});

