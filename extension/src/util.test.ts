	const instance = { uuid: 'FP-1', libraryUuid: 'LIB-A', name: ' r0603 ' };
	assert.equal(footprintMatchesInstance(instance, { footprint: { uuid: 'FP-1', libraryUuid: 'LIB-A', name: 'renamed' } }), true);
