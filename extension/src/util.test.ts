// Real native FOOTPRINT rows from the Hongen project export, with user/client/
// timestamp metadata removed. Geometry and DOCHEAD→META.source are retained.
const nativeFootprintFixture = readFileSync(join(__dirname, 'testdata/hongen-footprint-source.efoo'), 'utf8');
const nativeInstanceUuid = 'abe23dba1def1246';
const nativeAssetUuid = '20c29e37a9b84b4197418483096f9c05';
const nativeAssetLibrary = '0819f05c4eef4c71ace90d822a990e87';
const nativeInventory = (source = nativeFootprintFixture) => [{ footprintUuid: nativeInstanceUuid, documentSource: source }];

test('native footprint source: captured DOCHEAD and META map the instance to its exact library asset', () => {
	assert.deepEqual(readNativeFootprintSource(nativeInventory(), nativeInstanceUuid), {
		source: { instanceUuid: nativeInstanceUuid, uuid: nativeAssetUuid, libraryUuid: nativeAssetLibrary },
	});
	assert.equal(readNativeFootprintSource(nativeInventory(nativeFootprintFixture.replaceAll('\n', '\r\n')), nativeInstanceUuid).source?.uuid, nativeAssetUuid);
	assert.equal(readNativeFootprintSource(nativeInventory(nativeFootprintFixture.trim().slice(0, -1)), nativeInstanceUuid).source?.uuid, nativeAssetUuid, 'the final native row separator is optional at EOF');
});

test('native footprint source: unrelated footprints without origin do not poison an explicit target mapping', () => {
	const inventory = [...nativeInventory(), { footprintUuid: '1111111111111111', documentSource: 'unavailable unrelated source' }];
	assert.equal(readNativeFootprintSource(inventory, nativeInstanceUuid).source?.uuid, nativeAssetUuid);
});

const nativeRows = nativeFootprintFixture.trim().split('\n');
const nativeSourceFailures: Array<[string, unknown]> = [
	['missing inventory', undefined],
	['missing target', []],
	['duplicated target inventory', [...nativeInventory(), ...nativeInventory()]],
	['wrong DOCHEAD instance', nativeInventory(nativeFootprintFixture.replace(nativeInstanceUuid, '1111111111111111'))],
	['wrong DOCHEAD domain', nativeInventory(nativeFootprintFixture.replace('"docType":"FOOTPRINT"', '"docType":"DEVICE"'))],
	['16-hex source asset', nativeInventory(nativeFootprintFixture.replace(nativeAssetUuid, nativeInstanceUuid))],
	['missing source library', nativeInventory(nativeFootprintFixture.replace(`|${nativeAssetLibrary}`, '|'))],
	['extra source token', nativeInventory(nativeFootprintFixture.replace(`|${nativeAssetLibrary}`, `|${nativeAssetLibrary}|extra`))],
	['malformed row', nativeInventory(nativeFootprintFixture + 'not a native row\n')],
	['duplicate META', nativeInventory(nativeFootprintFixture + nativeRows[nativeRows.length - 1] + '\n')],
	['META before DOCHEAD', nativeInventory([nativeRows[nativeRows.length - 1], ...nativeRows.slice(0, -1)].join('\n'))],
	['no DOCHEAD', nativeInventory(nativeRows.slice(1).join('\n'))],
	['no META', nativeInventory(nativeRows.slice(0, -1).join('\n'))],
	['source in an ATTR instead of META', nativeInventory(nativeFootprintFixture.replace('"type":"META"', '"type":"ATTR"'))],
	['multiple source documents', nativeInventory(nativeFootprintFixture + nativeFootprintFixture)],
];
for (const [reason, inventory] of nativeSourceFailures) {
	test(`native footprint source: refuses ${reason}`, () => {
		const parsed = readNativeFootprintSource(inventory, nativeInstanceUuid);
		assert.equal(parsed.source, undefined);
		assert.ok(parsed.error);
	});
}
