// ── classifyWireConnectivity (dangling-wire / issue #51) ────────────────────

test('classifyWireConnectivity: orphan stub — one end on pin, other free, auto-net → orphan-stub', () => {
	// This is the issue #51 case: connect_pin built pin→wire→flag, flag deleted,
	// stub残留. Pin end touches a pin, far end touches nothing, net is $3N308.
	const ends = [
		{ touchesPin: true, touchesMarker: false },
		{ touchesPin: false, touchesMarker: false },
	];
	assert.equal(classifyWireConnectivity(ends, '$3N308'), 'orphan-stub');
});

test('classifyWireConnectivity: one end on pin, far end free, REAL net → connected (mid-route, no false positive)', () => {
	const ends = [
		{ touchesPin: true, touchesMarker: false },
		{ touchesPin: false, touchesMarker: false },
	];
	assert.equal(classifyWireConnectivity(ends, 'VCC'), 'connected');
});

test('classifyWireConnectivity: one end on pin, far end free, BLANK net → orphan-stub (live-verified regression, 2026-07-07)', () => {
	// A connect_pin stub's wire.getState_Net() is '' on this build whether its
	// flag is intact or deleted — an INTACT stub never reaches this branch (its
	// far end touches the flag → anyMarker short-circuits to 'connected' first).
	// So reaching here with a blank net (not just the never-observed $-pattern)
	// is the real orphan signal; the original fix only checked isAutoGeneratedNet
	// and silently missed every real orphan on this build.
	const ends = [
		{ touchesPin: true, touchesMarker: false },
		{ touchesPin: false, touchesMarker: false },
	];
	assert.equal(classifyWireConnectivity(ends, ''), 'orphan-stub');
});

